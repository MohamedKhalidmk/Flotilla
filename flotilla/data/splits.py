# Sources: gsm8k, math500, matharena, gpqa, ifeval, mmmu, ocrbench, livecodebench, lmms-eval (docs/reference/REFERENCES.md)
"""Small-test (dev) and test splits (protocol 2): seeded draw, 5% of items, at least 20 per benchmark.
RULER is built separately by flotilla.data.export_ruler (its items are generated by lm-eval).

    python -m flotilla.data.splits --splits-dir configs/splits --export-dir $SCRATCH/flotilla/smalltest
Writes configs/splits/<bench>.json ({bench, seed, n_total, dev, test, source}) and, for dev items only,
<export-dir>/<bench>.jsonl: {item_id, bench, task_type, task, gold, options?, images?, public_tests?, ...}.
"""
import argparse
import base64
import io
import json
import random
from pathlib import Path

from huggingface_hub import snapshot_download

from flotilla.data.data import load as load_dataset
from flotilla.legacy.router_data import _lcb_private

SEED = 20261119
LCB_WINDOW = ("2024-08-01", "2025-05-01")   # protocol 1.3, release_v6
MMMU_MC = "Answer with the option's letter from the given choices directly."     # lmms-eval 0.7.3 mmmu_val defaults
MMMU_OPEN = "Answer the question using a single word or phrase."


def n_dev(n: int) -> int:
    return max(20, int(n * 0.05 + 0.5))


def png_b64(img) -> str:
    buf = io.BytesIO()
    img.convert("RGB").save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode()


def gsm8k():
    for i, ex in enumerate(load_dataset("openai/gsm8k", "main", split="test")):
        yield {"item_id": f"gsm8k/{i}", "task_type": "math", "task": ex["question"],
               "gold": ex["answer"].split("####")[-1].strip().replace(",", ""), "scorer": "math_verify"}


def math500():
    for ex in load_dataset("HuggingFaceH4/MATH-500", split="test"):
        yield {"item_id": f"math500/{ex['unique_id']}", "task_type": "math", "task": ex["problem"], "gold": ex["answer"],
               "scorer": "math_verify"}


def aime(year: int):
    def gen():
        for ex in load_dataset(f"MathArena/aime_{year}", split="train"):
            yield {"item_id": f"aime{year}/{ex['problem_idx']}", "task_type": "math", "task": ex["problem"],
                   "gold": str(ex["answer"]), "scorer": "math_verify"}
    return gen


def gpqa():
    for ex in load_dataset("Idavidrein/gpqa", "gpqa_diamond", split="train"):
        rid = ex["Record ID"]
        opts = [ex["Correct Answer"]] + [ex[f"Incorrect Answer {k}"] for k in (1, 2, 3)]
        opts = [o.strip() for o in opts]
        order = list(range(4))
        random.Random(f"{SEED}-{rid}").shuffle(order)   # fixed per item, recorded by the seed
        shuffled = [opts[k] for k in order]
        gold = chr(65 + order.index(0))
        task = ex["Question"].strip() + "\n\n" + "\n".join(f"{chr(65 + k)}. {o}" for k, o in enumerate(shuffled))
        yield {"item_id": f"gpqa/{rid}", "task_type": "science_mc", "task": task, "options": shuffled, "gold": gold,
               "scorer": "mc_letter"}


def ifeval():
    for ex in load_dataset("google/IFEval", split="train"):
        yield {"item_id": f"ifeval/{ex['key']}", "task_type": "instruction", "task": ex["prompt"], "gold": None,
               "instruction_id_list": ex["instruction_id_list"], "kwargs": ex["kwargs"], "scorer": "ifeval"}


def mmmu():
    import ast
    for ex in load_dataset("lmms-lab/MMMU", split="validation"):
        opts = ast.literal_eval(ex["options"]) if ex["options"] else []
        imgs = [png_b64(ex[f"image_{k}"]) for k in range(1, 8) if ex.get(f"image_{k}") is not None]
        if ex["question_type"] == "multiple-choice" and opts:
            task = ex["question"] + "\n" + "\n".join(f"{chr(65 + k)}. {o}" for k, o in enumerate(opts)) + "\n" + MMMU_MC
        else:
            task = ex["question"] + "\n" + MMMU_OPEN
        yield {"item_id": f"mmmu/{ex['id']}", "task_type": "vision", "task": task, "options": opts or None, "gold": ex["answer"],
               "question_type": ex["question_type"], "images": imgs, "scorer": "mmmu"}


def ocrbench():
    for i, ex in enumerate(load_dataset("echo840/OCRBench", split="test")):
        gold = ex["answer"] if isinstance(ex["answer"], list) else [ex["answer"]]
        yield {"item_id": f"ocrbench/{i}", "task_type": "vision", "task": ex["question"], "gold": gold,
               "ocr_type": ex["question_type"], "ocr_dataset": ex["dataset"], "images": [png_b64(ex["image"])], "scorer": "ocrbench"}


def lcb():
    root = Path(snapshot_download("livecodebench/code_generation_lite", repo_type="dataset", local_files_only=True))
    for f in sorted(root.glob("test*.jsonl")):
        for line in open(f):
            ex = json.loads(line)
            if not (LCB_WINDOW[0] <= ex["contest_date"][:10] <= LCB_WINDOW[1]):
                continue
            public = json.loads(ex["public_test_cases"])
            meta = json.loads(ex["metadata"]) if ex.get("metadata") else {}
            stdin = all(t.get("testtype") == "stdin" for t in public)
            task = ex["question_content"]
            if ex.get("starter_code"):
                task += "\n\nUse this starter code:\n```python\n" + ex["starter_code"] + "\n```"
            elif stdin:
                task += "\n\nRead from standard input and write to standard output."
            yield {"item_id": f"lcb/{ex['question_id']}", "task_type": "code", "task": task, "gold": None,
                   "contest_date": ex["contest_date"][:10], "difficulty": ex.get("difficulty"), "platform": ex.get("platform"),
                   "starter_code": ex.get("starter_code") or "", "fn_name": meta.get("func_name"),
                   "public_tests": public if stdin else None, "all_tests": public + _lcb_private(ex["private_test_cases"]),
                   "scorer": "lcb"}


BENCHES = {"gsm8k": gsm8k, "math500": math500, "aime2025": aime(2025), "aime2026": aime(2026), "gpqa": gpqa,
           "ifeval": ifeval, "mmmu": mmmu, "ocrbench": ocrbench, "lcb": lcb}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--splits-dir", required=True)
    ap.add_argument("--export-dir", required=True)
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--all-items", action="store_true",
                    help="full runs: export every item (dev and test); the split files are checked, never rewritten")
    a = ap.parse_args()
    sd, ed = Path(a.splits_dir), Path(a.export_dir)
    sd.mkdir(parents=True, exist_ok=True)
    ed.mkdir(parents=True, exist_ok=True)
    for name, fn in BENCHES.items():
        if a.only and name not in a.only:
            continue
        items = list(fn())
        ids = [it["item_id"] for it in items]
        assert len(ids) == len(set(ids)), f"{name}: duplicate ids"
        dev = set(random.Random(f"{SEED}-{name}").sample(ids, n_dev(len(ids))))
        if a.all_items:  # the frozen split must reproduce exactly
            frozen = json.loads((sd / f"{name}.json").read_text())
            assert set(frozen["dev"]) == dev and frozen["n_total"] == len(ids), f"{name}: split does not reproduce"
            with open(ed / f"{name}.jsonl", "w") as f:
                for it in items:
                    f.write(json.dumps({"bench": name, **it, "split": "dev" if it["item_id"] in dev else "test"},
                                       ensure_ascii=False) + "\n")
            print(f"{name}: all {len(ids)} items (dev {len(dev)})", flush=True)
            continue
        (sd / f"{name}.json").write_text(json.dumps({
            "bench": name, "seed": SEED, "n_total": len(ids), "n_dev": len(dev),
            "dev": [i for i in ids if i in dev], "test": [i for i in ids if i not in dev], "created": "2026-11-19"}, indent=1))
        with open(ed / f"{name}.jsonl", "w") as f:
            for it in items:
                if it["item_id"] in dev:
                    f.write(json.dumps({"bench": name, **it}, ensure_ascii=False) + "\n")
        print(f"{name}: total {len(ids)}, dev {len(dev)}", flush=True)


if __name__ == "__main__":
    main()
